# Packs the Character Gallery art (portraits 48x56 + 16x24 sprite sheets) into one atlas: assets/chars.png
# Each character is one 84x76 row: portrait at (0,0), sheet (32x72: idle, walk front, walk side) at (52,0); the gaps stop pixels bleeding.
import json, os
from PIL import Image
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..')
IDS = 'yirui yishuo xiaotian liuhanyan kuchan tuqianqiu wudadan wenduizhang chutiankuo niubaobao huotianxia aman baixian jiabafang hubanxian heixiong daoba shouhou'.split()
GAL = os.environ.get('GALLERY', 'C:/CharacterGallery/chars')
im = Image.new('RGBA', (84, 76 * len(IDS)), (0, 0, 0, 0))
for i, cid in enumerate(IDS):
    src = os.path.join(ROOT, 'assets', 'chars', cid)
    p = Image.open(os.path.join(src, 'portrait.png')).convert('RGBA')
    s = Image.open(os.path.join(src, 'sheet.png')).convert('RGBA')
    im.paste(p, (0, 76 * i)); im.paste(s, (52, 76 * i))
im.save(os.path.join(ROOT, 'assets', 'chars.png'), optimize=True)
with open(os.path.join(ROOT, 'js', 'atlas.js'), 'w', encoding='utf-8') as f:
    f.write('// generated by tools/atlas.py: row index of each character in assets/chars.png (84x76 per row)\n')
    f.write('export const ATLAS = ' + json.dumps({c: i for i, c in enumerate(IDS)}) + ';\n')
print('atlas', im.size)
