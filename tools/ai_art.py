"""Brings in the AI-painted art made for Longmen Tactics (C:\\LongmenTactics, tools/ai_art.py and tools/ai_chibi.py).

    C:/sdenv/Scripts/python tools/ai_art.py

    assets/ai/por/<id>.webp    the portrait, 240 x 280 (the 6:7 frame of the pixel portraits), transparent
    assets/ai/fig/<id>.webp    the figure: front, side and back side by side, 160 x 200 each, feet on the bottom row;
                               the side view faces right, like the pixel sheets
    js/ai_art.js               AI_POR and AI_FIG: id -> a short hash of the file, used to bust the cache

Run it again whenever more paintings arrive: finished figures are kept, new ones are cut, and paintings still being
written are skipped. Characters with no painting keep their pixel art from assets/chars.png.
"""
import hashlib, json, os, sys
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TAC = 'C:/LongmenTactics'
sys.path.insert(0, os.path.join(TAC, 'tools'))
import ai_chibi  # noqa: E402

CW, CH = 160, 200
ai_chibi.H, ai_chibi.MAXW = CH - 2, CW - 2
IDS = 'yirui yishuo xiaotian liuhanyan kuchan tuqianqiu wudadan wenduizhang chutiankuo niubaobao huotianxia aman baixian jiabafang hubanxian heixiong daoba shouhou'.split()


def tag(path):
    with open(path, 'rb') as f:
        return hashlib.md5(f.read()).hexdigest()[:8]


def main():
    por_dir, fig_dir = (os.path.join(ROOT, 'assets', 'ai', d) for d in ('por', 'fig'))
    os.makedirs(por_dir, exist_ok=True)
    os.makedirs(fig_dir, exist_ok=True)
    cut, raw = os.path.join(TAC, 'art', 'cut'), os.path.join(TAC, 'art', 'chibi')
    por, fig = {}, {}
    for k in IDS:
        src, dst = os.path.join(cut, k + '_portrait.webp'), os.path.join(por_dir, k + '.webp')
        if os.path.exists(src) and not (os.path.exists(dst) and os.path.getmtime(dst) > os.path.getmtime(src)):
            try:
                im = Image.open(src).convert('RGBA')
            except OSError:  # still being written
                im = None
            if im:
                w = round(im.height * 6 / 7)
                im = im.crop(((im.width - w) // 2, 0, (im.width - w) // 2 + w, im.height)).resize((240, 280), Image.LANCZOS)
                im.save(dst, quality=90, method=6)
        if os.path.exists(dst):
            por[k] = tag(dst)
        dst = os.path.join(fig_dir, k + '.webp')
        srcs = [os.path.join(raw, f'{k}_{v}.png') for v in ('front', 'side', 'back')]
        if all(os.path.exists(s) for s in srcs) and not (os.path.exists(dst) and os.path.getmtime(dst) > max(map(os.path.getmtime, srcs))):
            try:
                views = [ai_chibi.cut(Image.open(s)) for s in srcs]
            except (OSError, ValueError):  # still being painted
                views = [None]
            if all(views):
                views[1] = views[1].transpose(Image.FLIP_LEFT_RIGHT)   # painted looking left; the sheets' side views face right
                strip = Image.new('RGBA', (CW * 3, CH))
                for i, im in enumerate(views):
                    strip.alpha_composite(im, (i * CW + (CW - im.width) // 2, CH - 1 - im.height))
                strip.save(dst, quality=90, method=6)
        if os.path.exists(dst):
            fig[k] = tag(dst)
    with open(os.path.join(ROOT, 'js', 'ai_art.js'), 'w', encoding='utf-8') as fh:
        fh.write('// generated by tools/ai_art.py: the characters with AI-painted art in assets/ai/ (id -> file hash). Do not edit by hand.\n')
        fh.write(f'export const AI_POR = {json.dumps(por)};\n')
        fh.write(f'export const AI_FIG = {json.dumps(fig)};\n')
    print(len(por), 'portraits,', len(fig), 'figures; still pixel art:', ' '.join(k for k in IDS if k not in fig) or 'none')


if __name__ == '__main__':
    main()
