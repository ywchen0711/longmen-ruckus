try { const l = localStorage.getItem('lr-lang'); if (l === 'en' || l === 'zh') LANG.cur = l; else if (!/^zh/i.test(navigator.language || '')) LANG.cur = 'en'; } catch (e) { /* private mode */ }
// pick the current language from {zh, en} (or a plain string) and fill {placeholders}
export function L(o, vars) {
  let s = o == null ? '' : typeof o === 'string' ? o : (o[LANG.cur] ?? o.zh ?? '');
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => { const v = vars[k]; return v == null ? m : typeof v === 'object' ? L(v) : v; });
  return s;
}
